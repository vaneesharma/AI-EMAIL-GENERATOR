from django.conf import settings
from django.db import models

# Dropdown options shared by the forms. The stored value is the same text
# that the user sees, so it is easy to read in MySQL and in the admin panel.
PURPOSES = [
    "Job Application", "Internship Application", "Leave Request", "College Request",
    "Meeting Request", "Complaint", "Follow-up", "Thank You", "Client Communication",
]
CUSTOM_PURPOSE = "Custom"
RECIPIENTS = ["HR", "Teacher", "Manager", "Client", "Professor", "Recruiter", "Other"]
TONES = ["Professional", "Formal", "Friendly", "Polite", "Simple"]
LANGUAGES = ["English", "Hindi", "Hinglish"]


def as_choices(values):
    return [(value, value) for value in values]


class GeneratedEmail(models.Model):
    """One email generated by the AI for a particular user."""

    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="generated_emails",
    )
    purpose = models.CharField(max_length=100)
    recipient_type = models.CharField(max_length=50)
    tone = models.CharField(max_length=50)
    language = models.CharField(max_length=50)
    important_points = models.TextField()
    additional_instructions = models.TextField(blank=True)
    subject = models.CharField(max_length=255)
    body = models.TextField()
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["-created_at"]

    def __str__(self):
        return f"{self.subject} ({self.user})"

    @property
    def preview(self):
        """First ~120 characters of the body, on one line."""
        text = " ".join(self.body.split())
        return text if len(text) <= 120 else text[:117] + "..."
